#!/usr/bin/env python3
"""Argentina vector illustration authored as DesignCraft native editable paths.
No SVG import, no image placement, no image-generation backend.
Each contour is drawn through path.create; holes are made using makeCompoundPath.
"""
import base64,collections,json,pathlib,subprocess,sys,zipfile,zlib

root=pathlib.Path(sys.argv[1]).resolve()
root.mkdir(parents=True,exist_ok=True)
packed=(root.parent/"geometry.zb64").read_text(encoding="ascii").strip()
shapes=json.loads(zlib.decompress(base64.b64decode(packed)))
assert len(shapes)>600 and all("parts" in x for x in shapes)
colors=sorted(set(s["color"] for s in shapes))
steps=[]
def push(command,params):
    i=len(steps)
    steps.append((command,params))
    return i
push("file.new",{"width":615,"height":615,"pages":1,"facingPages":False,"margins":0,"title":"ARGENTINA | ilustración vectorial editable"})
for i,color in enumerate(colors):
    push("swatch.create",{"name":f"Color_{i:02d}","color":color})
color_swatch={c:f"Color_{i:02d}" for i,c in enumerate(colors)}
# The new object defaults are filled with no stroke, using the engine's own paint command.
push("object.stroke",{"swatch":"[None]"})
# Only graphic primitives generated by genuine DesignCraft drawing calls.
labels=sorted(set(s["layer"] for s in shapes))
for label in labels:
    index=push("layer.new",{"name":label})
    push("layer.activate",{"id":f"${index}.id"})
    for entry in [x for x in shapes if x["layer"]==label]:
        ids=[]
        for p in entry["parts"]:
            if len(p)>1400:  # no path exceeds the engine's safe point budget
                raise RuntimeError("Overlong contour")
            i=push("path.create",{"anchors":[{"p":xy} for xy in p],"closed":True})
            ids.append(f"${i}.id")
        if len(ids)>1:
            push("object.makeCompoundPath",{"ids":ids})
        push("object.fill",{"swatch":color_swatch[entry["color"]]})
# Persist complete editable native document and PNG/PDF using the official CLI.
script=root/"native-designcraft.dcs"
script.write_text("\n".join(cmd+" "+json.dumps(params,separators=(",",":"),ensure_ascii=False) for cmd,params in steps)+"\n",encoding="utf-8")
out=root/"Argentina_REHECHO_DesignCraft.designcraft"
png=root/"Argentina_REHECHO_DesignCraft.png"
pdf=root/"Argentina_REHECHO_DesignCraft.pdf"
proc=subprocess.run(["designcraft-cli","script",str(script),"--save",str(out),"--export",str(png),"--export",str(pdf)],
  text=True,capture_output=True,timeout=600)
(root/"run.log").write_text(proc.stdout[-10000:]+"\n"+proc.stderr[-15000:],encoding="utf-8")
print("Native DesignCraft exit",proc.returncode,"object instructions",len(steps),"paths",sum(len(s['parts']) for s in shapes))
if proc.returncode!=0:
    print((proc.stdout+proc.stderr)[-7000:])
    sys.exit(proc.returncode)
for p in [out,png,pdf]:
    assert p.exists() and p.stat().st_size>1000,p
with zipfile.ZipFile(out) as z:
    j=json.loads(z.read("document.json"))
shapecount=collections.Counter()
def rec(o):
    if isinstance(o,dict):
        v=o.get("shape")
        if isinstance(v,str):shapecount[v]+=1
        for t in o.values():rec(t)
    elif isinstance(o,list):
        for t in o:rec(t)
rec(j)
# DesignCraft's compressed document package is native; there must be no bitmap assets.
assert shapecount["path"]>=600,shapecount
assert len(j.get("assets",[]))==0, "Unexpected raster image"
report={"status":"PASS","editor":"DesignCraft 0.17.2 official","native_shapes":dict(shapecount),
  "source_vector_objects":len(shapes),"source_contours":sum(len(s["parts"]) for s in shapes),
  "native_operations":len(steps),"raster_assets":0,
  "files":{x.name:x.stat().st_size for x in [out,png,pdf]}}
(root/"QA.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
print("PASS",json.dumps(report))
